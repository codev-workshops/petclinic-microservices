package org.springframework.samples.petclinic.customers.contracts;

import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.Date;
import java.util.List;
import java.util.Optional;

import io.restassured.module.mockmvc.RestAssuredMockMvc;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.context.annotation.Import;
import org.springframework.samples.petclinic.customers.model.Owner;
import org.springframework.samples.petclinic.customers.model.OwnerRepository;
import org.springframework.samples.petclinic.customers.model.Pet;
import org.springframework.samples.petclinic.customers.model.PetRepository;
import org.springframework.samples.petclinic.customers.model.PetType;
import org.springframework.samples.petclinic.customers.web.mapper.OwnerEntityMapper;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.test.web.servlet.MockMvc;

import static org.mockito.ArgumentMatchers.any;
import static org.mockito.BDDMockito.given;

/**
 * Base class for the provider tests generated by Spring Cloud Contract from {@code src/test/resources/contracts}.
 */
@WebMvcTest
@Import(OwnerEntityMapper.class)
@ActiveProfiles("test")
public abstract class ContractVerifierBase {

    @Autowired
    MockMvc mockMvc;

    @MockitoBean
    OwnerRepository ownerRepository;

    @MockitoBean
    PetRepository petRepository;

    @BeforeEach
    void setUp() {
        RestAssuredMockMvc.mockMvc(mockMvc);

        PetType cat = petType(1, "cat");
        PetType dog = petType(2, "dog");
        PetType lizard = petType(3, "lizard");

        Owner george = owner(1, "George", "Franklin", "110 W. Liberty St.", "Madison", "6085551023");
        Pet leo = new Pet();
        leo.setId(1);
        leo.setName("Leo");
        leo.setBirthDate(date(2010, 9, 7));
        leo.setType(cat);
        george.addPet(leo);

        Owner betty = owner(2, "Betty", "Davis", "638 Cardinal Ave.", "Sun Prairie", "6085551749");
        Pet basil = new Pet();
        basil.setId(2);
        basil.setName("Basil");
        basil.setBirthDate(date(2012, 8, 6));
        basil.setType(petType(6, "hamster"));
        betty.addPet(basil);

        given(ownerRepository.findById(1)).willReturn(Optional.of(george));
        given(ownerRepository.findAll()).willReturn(List.of(george, betty));
        given(ownerRepository.save(any(Owner.class))).willAnswer(invocation -> {
            Owner saved = invocation.getArgument(0);
            ReflectionTestUtils.setField(saved, "id", 11);
            return saved;
        });

        given(petRepository.findPetTypes()).willReturn(List.of(cat, dog, lizard));
        given(petRepository.findPetTypeById(2)).willReturn(Optional.of(dog));
        given(petRepository.save(any(Pet.class))).willAnswer(invocation -> {
            Pet saved = invocation.getArgument(0);
            saved.setId(14);
            return saved;
        });
    }

    private static Owner owner(int id, String firstName, String lastName, String address, String city, String telephone) {
        Owner owner = new Owner();
        ReflectionTestUtils.setField(owner, "id", id);
        owner.setFirstName(firstName);
        owner.setLastName(lastName);
        owner.setAddress(address);
        owner.setCity(city);
        owner.setTelephone(telephone);
        return owner;
    }

    private static PetType petType(int id, String name) {
        PetType type = new PetType();
        type.setId(id);
        type.setName(name);
        return type;
    }

    private static Date date(int year, int month, int day) {
        return Date.from(LocalDate.of(year, month, day).atStartOfDay(ZoneOffset.UTC).toInstant());
    }
}
