package org.springframework.samples.petclinic.visits.contracts;

import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.Date;
import java.util.List;

import io.restassured.module.mockmvc.RestAssuredMockMvc;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.samples.petclinic.visits.model.Visit;
import org.springframework.samples.petclinic.visits.model.VisitRepository;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.web.servlet.MockMvc;

import static org.mockito.BDDMockito.given;

/**
 * Base class for the provider tests generated by Spring Cloud Contract from {@code src/test/resources/contracts}.
 */
@WebMvcTest
@ActiveProfiles("test")
public abstract class ContractVerifierBase {

    @Autowired
    MockMvc mockMvc;

    @MockitoBean
    VisitRepository visitRepository;

    @BeforeEach
    void setUp() {
        RestAssuredMockMvc.mockMvc(mockMvc);

        given(visitRepository.findByPetIdIn(List.of(1, 2))).willReturn(List.of(
            visit(1, 1, date(2013, 1, 1), "rabies shot"),
            visit(2, 2, date(2013, 1, 2), "neutered")
        ));
    }

    private static Visit visit(int id, int petId, Date date, String description) {
        return Visit.VisitBuilder.aVisit().id(id).petId(petId).date(date).description(description).build();
    }

    private static Date date(int year, int month, int day) {
        return Date.from(LocalDate.of(year, month, day).atStartOfDay(ZoneOffset.UTC).toInstant());
    }
}
