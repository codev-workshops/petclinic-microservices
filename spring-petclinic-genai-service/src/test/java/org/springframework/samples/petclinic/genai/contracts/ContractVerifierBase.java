package org.springframework.samples.petclinic.genai.contracts;

import io.restassured.module.mockmvc.RestAssuredMockMvc;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.memory.ChatMemory;
import org.springframework.samples.petclinic.genai.PetclinicChatClient;

import static org.mockito.Answers.RETURNS_DEEP_STUBS;
import static org.mockito.Answers.RETURNS_SELF;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.BDDMockito.given;
import static org.mockito.Mockito.mock;

/**
 * Base class for the provider tests generated by Spring Cloud Contract from {@code src/test/resources/contracts}.
 * The LLM is replaced by a mocked {@link ChatClient} so the HTTP contract of {@code POST /chatclient} is verified
 * without calling an AI provider.
 */
public abstract class ContractVerifierBase {

    @BeforeEach
    void setUp() {
        ChatClient chatClient = mock(ChatClient.class, RETURNS_DEEP_STUBS);
        given(chatClient.prompt().user(anyString()).call().content())
            .willReturn("We have James Carter and Helen Leary.");

        ChatClient.Builder builder = mock(ChatClient.Builder.class, RETURNS_SELF);
        given(builder.build()).willReturn(chatClient);

        RestAssuredMockMvc.standaloneSetup(new PetclinicChatClient(builder, mock(ChatMemory.class), null));
    }
}
