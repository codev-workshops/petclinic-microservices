package org.springframework.samples.petclinic.vets.contracts;

import java.util.List;

import io.restassured.module.mockmvc.RestAssuredMockMvc;
import org.junit.jupiter.api.BeforeEach;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.WebMvcTest;
import org.springframework.samples.petclinic.vets.model.Specialty;
import org.springframework.samples.petclinic.vets.model.Vet;
import org.springframework.samples.petclinic.vets.model.VetRepository;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.test.web.servlet.MockMvc;

import static org.mockito.BDDMockito.given;

/**
 * Base class for the provider tests generated by Spring Cloud Contract from {@code src/test/resources/contracts}.
 */
@WebMvcTest
@ActiveProfiles("test")
public abstract class ContractVerifierBase {

    @Autowired
    MockMvc mockMvc;

    @MockitoBean
    VetRepository vetRepository;

    @BeforeEach
    void setUp() {
        RestAssuredMockMvc.mockMvc(mockMvc);

        Vet carter = vet(1, "James", "Carter");
        Vet leary = vet(2, "Helen", "Leary");
        carter.addSpecialty(specialty(2, "surgery"));
        leary.addSpecialty(specialty(1, "radiology"));

        given(vetRepository.findAll()).willReturn(List.of(carter, leary));
    }

    private static Specialty specialty(int id, String name) {
        Specialty specialty = new Specialty();
        ReflectionTestUtils.setField(specialty, "id", id);
        specialty.setName(name);
        return specialty;
    }

    private static Vet vet(int id, String firstName, String lastName) {
        Vet vet = new Vet();
        vet.setId(id);
        vet.setFirstName(firstName);
        vet.setLastName(lastName);
        return vet;
    }
}
